export function financialMetricName(label: string) {
  const clean = label
    .replace(/from \(used in\)/gi, "from used in")
    .replace(/\s+/g, " ")
    .replace(/\s*\[(?:abstract|line items)\]$/i, "")
    .trim();
  return definitions.find(([, re]) => re.test(clean))?.[0] ?? null;
}
export const monetaryMetric = (name: string) =>
  !/(?:EPS|margin|NPA|adequacy|Credit cost)/i.test(name);
export const headlineMetrics = ["Revenue", "EBITDA", "PBT", "PAT"];
export function financialSector(company: {
  ticker: string;
  name?: string;
  sector?: string;
}) {
  return /\bbanks?\b|banking|insurance|financial services|\bnbfc\b/i.test(
    `${company.name ?? ""} ${company.sector ?? ""}`,
  ) || /BANK\.NS$/.test(company.ticker)
    ? "financial"
    : "nonfinancial";
}
