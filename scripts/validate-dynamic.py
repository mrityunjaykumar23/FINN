"""Independent Decimal audit of newly imported DMART quarter comparisons.

Values below were checked directly against the two authentic NSE press releases,
not generated by the TypeScript extractor. Requires the documented local imports.
"""
from decimal import Decimal
from urllib.request import urlopen
import json
base='http://127.0.0.1:5173/api/'
data=json.load(urlopen(base+'companies/DMART.NS/overview'))
expected={'Revenue':(14872,15973,12727),'EBITDA':(955,1217,944),'PAT':(551,724,563)}
periods=['Q4 FY2025','Q3 FY2025','Q4 FY2024']
checked=0
for name,values in expected.items():
 for period,value in zip(periods,values):
  metric=next(m for m in data['metrics'] if m['name']==name and m['period']==period and m['basis']=='Consolidated reported INR')
  assert metric['value']==value,(name,period,metric['value'],value)
  document=json.load(urlopen(base+'documents/'+metric['document_id']))
  text=next(p['text'] for p in document['pages'] if p['page']==metric['page']).replace(',','')
  assert str(value) in text,(name,period,'missing source number')
  checked+=1
 current,previous,prior=map(Decimal,values)
 print(name,'QoQ',round((current-previous)/previous*100,6),'YoY',round((current-prior)/prior*100,6))
assert not any(m['name']=='PBT' and m['period']=='Q4 FY2025' for m in data['metrics'])
print(f'Independently verified {checked} consolidated metric values and 6 percentage calculations; PBT remains unavailable.')
